    هيٺيون = (بنانشان)(-1);       /* trigger new sub-table when len > root */
    استعمال_ٿيل = 1U << پاڙ;          /* use root table entries */
    نقاب = استعمال_ٿيل - 1;            /* mask for comparing low */

